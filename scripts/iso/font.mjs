/** The font as floor.json carries it: height, spacing, glyphs as rows of "#" and ".". */
export function signFont() {
  for (const [char, rows] of Object.entries(G)) {
    if (rows.length !== 7 || rows.some((row) => row.length !== rows[0].length)) throw new Error(`glyph ${char} is not 7 even rows`);
  }
  return { height: 7, spacing: 1, glyphs: G };
}
